// scripts/gen-topic-data.js
// 在 webpack 打包「之前」先把最新的词页数据落地为 src/data/topicPages.ts，
// 确保 webpack 打进 SPA bundle 的 BY_SLUG 始终包含全部（含新增）词页 slug，
// 避免「直接访问 .html 静态页正常、但 SPA 路由（站内链接/不带 .html）报页面不存在」的问题。
// 用法：npm run build 内部会自动调用（见 package.json）。
const fs = require('fs');
const path = require('path');

const topicPages = require('./topic-pages').concat(require('./topic-pages-extra'));
// GEO：统一兜底 topic 页「最后更新」日期；单页可在 topic-pages.js / topic-pages-extra.js 设 updated 覆盖
topicPages.forEach(p => { if (!p.updated) p.updated = '2026-07-15'; });

const outDir = path.resolve(__dirname, '..', 'src', 'data');
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
const ts = `// AUTO-GENERATED by scripts/gen-topic-data.js — 请勿手改
// 改词页内容请编辑 scripts/topic-pages.js / topic-pages-extra.js 后重跑 npm run build

export const topicPages = ${JSON.stringify(topicPages, null, 2)};
`;
fs.writeFileSync(path.resolve(outDir, 'topicPages.ts'), ts);
console.log('✓ 已生成 src/data/topicPages.ts（' + topicPages.length + ' 个词页）');
